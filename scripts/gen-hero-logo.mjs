// Inlines public/brand/logo-compact-inverse.svg for the homepage hero.
//
// The logo is used as <img> everywhere else, where page CSS can't reach into
// the file. The hero pulses the dot (the <g class="tpof-dot"> group the
// package ships), and that needs the SVG in the DOM. This copies the file
// byte for byte into lib/hero-logo-svg.generated.ts — no edit of the artwork;
// tests/hero-logo.spec.ts fails if the generated copy ever drifts from the
// file in public/brand.
//
// Run after replacing the logo package:  node scripts/gen-hero-logo.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const svg = readFileSync(`${ROOT}public/brand/logo-compact-inverse.svg`, "utf8");
writeFileSync(
  `${ROOT}lib/hero-logo-svg.generated.ts`,
  `// GENERATED by scripts/gen-hero-logo.mjs from public/brand/logo-compact-inverse.svg — do not edit.\nexport const HERO_LOGO_SVG = ${JSON.stringify(svg)};\n`,
);
console.log(`lib/hero-logo-svg.generated.ts written (${svg.length} chars)`);
